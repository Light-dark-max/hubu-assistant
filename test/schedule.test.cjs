const assert = require('node:assert/strict');
const S = require('../app/src/main/assets/www/schedule.js');
assert.equal(S.currentWeek('2026-09-07',new Date(2026,9,23)),7);
assert.equal(S.currentWeek('2026-09-08',new Date(2026,9,23)),0);
assert.equal(S.currentWeek('2026-09-07',new Date(2026,8,6)),-1);
assert.equal(S.inWeek('1-16(单周)',7),true);
assert.equal(S.inWeek('1-16(单周)',8),false);
assert.equal(S.inWeek('1-4,8,10-12',8),true);
assert.equal(S.inWeek('1-4,8,10-12',9),false);
assert.equal(S.inWeek('2-16双周',10),true);
assert.deepEqual(S.sections({sections:'09-10-11'}),[9,10,11]);
const courses=[{name:'Friday',weekday:5,weeks:'1-16',sections:'05-06'},{name:'Ended',weekday:5,weeks:'1-4',sections:'01-02'},{name:'Thursday',weekday:4,weeks:'1-16',sections:'01-02'}];
assert.deepEqual(S.today(courses,'2026-09-07',new Date(2026,9,23)).map(c=>c.name),['Friday']);
assert.equal(S.time(courses[0],[{sections:[5,6],start:'14:00',end:'15:40'}],true),'15:40');
assert.equal(S.time({sections:'09-10'},[{sections:[9,10,11],start:'19:00',end:'21:35'}],true),'第10节');
assert.deepEqual(S.weeks('1–16'.replace('–','-')+'单周'),[1,3,5,7,9,11,13,15]);
assert.deepEqual(S.weeks('2-10（双周）'),[2,4,6,8,10]);
assert.deepEqual(S.weeks('1-3，5、8至9'),[1,2,3,5,8,9]);
assert.equal(S.canonicalWeeks([1,2,3,5,8,9]),'1-3,5,8-9');
assert.deepEqual(S.weekPattern('1-16（单周）'),{weeks:'1-16',pattern:'odd'});
assert.deepEqual(S.weekPattern('2,4,6,8,10,12,14,16'),{weeks:'2-16',pattern:'even'});
assert.deepEqual(S.weekPattern('1,3,7'),{weeks:'1,3,7',pattern:'all'});
assert.deepEqual(S.weekPattern('8'),{weeks:'8',pattern:'all'});
assert.equal(S.applyWeekPattern('1-16','odd'),'1,3,5,7,9,11,13,15');
assert.equal(S.applyWeekPattern('1-16','even'),'2,4,6,8,10,12,14,16');
assert.equal(S.applyWeekPattern('1-4,8,10-12','odd'),'1,3,11');
assert.equal(S.applyWeekPattern('1-16','all'),'1-16');
assert.throws(()=>S.applyWeekPattern('2','odd'),/没有上课周/);
assert.throws(()=>S.applyWeekPattern('1-16','bad'),/请选择/);
const oddRule=S.applyWeekPattern('1-16','odd');
assert.equal(S.today([{name:'单周课',weekday:1,weeks:oddRule,sections:'01-02'}],'2026-09-07',new Date(2026,8,7)).length,1);
assert.equal(S.today([{name:'单周课',weekday:1,weeks:oddRule,sections:'01-02'}],'2026-09-07',new Date(2026,8,14)).length,0);
for(const rule of ['0-16','1-31','5-2','abc','1-2垃圾','1单周,3双周'])assert.throws(()=>S.weeks(rule));
const original={name:'量子力学',weekday:1,weeks:'1-16',sections:'03-04',teacher:'老师',room:'A101'};
const changed={...original,weekday:3,room:'B202',color:'#12AbEf'};
const edit={index:0,original,scope:'week',week:8,course:changed};
const split=S.editCourses([original],edit);
assert.equal(original.weeks,'1-16');
assert.equal(split.length,2);
assert.equal(split[0].weeks,'1-7,9-16');
assert.equal(split[0].room,'A101');
assert.equal(split[1].weeks,'8');
assert.equal(split[1].weekday,3);
assert.equal(split[1].color,'#12abef');
assert.equal(S.editCourses([original],{...edit,scope:'all'})[0].weeks,'1-16');
assert.equal(S.editCourses([original],{...edit,remove:true})[0].weeks,'1-7,9-16');
assert.equal(S.editCourses([original],{...edit,scope:'all',remove:true}).length,0);
assert.equal(S.editCourses([{...original,weeks:'8'}],{...edit,original:{...original,weeks:'8'},remove:true}).length,0);
assert.equal(S.editCourses([],{...edit,index:-1,original:null}).length,1);
assert.throws(()=>S.editCourses([{...original,room:'新教室'}],edit),/已有变化/);
assert.throws(()=>S.cleanCourse({...changed,sections:'04-03'}),/节次/);
assert.throws(()=>S.cleanCourse({...changed,color:'bad'}),/颜色/);
assert.throws(()=>S.cleanCourse({...changed,name:''}),/课程名/);
assert.equal(S.courseColor(changed),'#12abef');
assert.match(S.courseColor(original),/^#[0-9a-f]{6}$/);
assert.deepEqual(S.colorStyle('#ffffff'),{background:'#ffffff',foreground:'#707070'});
console.log('Local schedule checks passed: date, weeks, split/edit/delete, stale data, validation and colors; no fee refresh was executed.');
