const assert=require('node:assert/strict');
const badge=require('../app/src/main/assets/www/task-badge.js');
const now=Date.UTC(2026,9,26,12),hour=3600000;
const task=(id,h,kind='homework')=>({id,kind,deadline:h===null?'':new Date(now+h*hour).toISOString()});
const tasks=[task('normal',5),task('exam',.5,'exam'),task('notice',null,'notice')];
assert.equal(badge.unread(tasks,[],now).length,3);
const seen=tasks.map(badge.key);
assert.deepEqual(badge.unread(tasks,seen,now).map(t=>t.id),['exam']);
assert.equal(badge.unread([tasks[0],tasks[2]],seen,now).length,0);
assert.equal(badge.unread([task('new',3)],seen,now).length,1);
assert.equal(badge.unread([task('normal',6)],seen,now).length,1);
const boundary=task('boundary',1),boundarySeen=[badge.key(boundary)];
assert.equal(badge.unread([boundary],boundarySeen,now).length,0);
assert.equal(badge.unread([boundary],boundarySeen,now+1).length,1);
assert.equal(badge.unread([boundary],boundarySeen,now+hour).length,0);
assert.equal(badge.unread([{...tasks[1],status:'已完成'}],seen,now).length,0);
assert.equal(badge.unread([task('expired',-1)],[],now).length,0);
assert.equal(badge.pending([{id:'unknown',deadline:'invalid'}],now).length,1);
assert.equal(badge.unread([tasks[0]],JSON.parse(JSON.stringify(seen)),now).length,0);
console.log('Task badge: viewing, new tasks, deadline changes, <1h boundary, expiration and persistence passed');
