const assert=require('node:assert/strict');
const {evaluate,hours}=require('../app/src/main/assets/www/task-reminders');
const time=(h)=>new Date(2026,9,27,h).getTime(),now=time(12),hour=3600000;
const task=(id,h)=>({id,kind:'homework',title:id,deadline:new Date(now+h*hour).toISOString()});
const settings={enabled:true,homework:'24, 6, 1',exam:'24, 1'};
let t=task('a',25),r=evaluate([t],null,settings,now);
assert.equal(r.alerts.length,0);r=evaluate([t],r.record,settings,now+2*hour);assert.equal(r.alerts.length,1);
let again=evaluate([t],r.record,settings,now+3*hour);assert.equal(again.alerts.length,0);
assert.equal(evaluate([t],r.record,settings,now+20*hour).alerts.length,1);
assert.equal(evaluate([t],r.record,settings,now+26*hour).alerts.length,0);
assert.equal(evaluate([t],r.record,{...settings,enabled:false},now+20*hour).alerts.length,0);
assert.equal(evaluate([{...t,status:'已完成'}],r.record,settings,now+20*hour).alerts.length,0);
assert.equal(evaluate([task('new',5)],r.record,settings,now).alerts.length,1);
assert.equal(evaluate([{...t,deadline:new Date(now+5*hour).toISOString()}],r.record,settings,now).alerts.length,1);
let late=task('late',13);r=evaluate([late],null,settings,now);
assert.equal(evaluate([late],r.record,settings,time(23)).alerts.length,0);
assert.equal(evaluate([late],r.record,settings,time(24)+.5*hour).alerts.length,1);
let quiet=task('quiet',30);r=evaluate([quiet],null,settings,now);
let q=evaluate([quiet],r.record,settings,time(23));assert.equal(q.alerts.length,0);
assert.equal(evaluate([quiet],q.record,settings,time(31)).alerts.length,1);
const notice={id:'notice',kind:'notice',title:'新通知',deadline:''};
const unknown={id:'unknown',kind:'homework',title:'时间未知',deadline:''};
let baseline=evaluate([],null,settings,now);
assert.equal(evaluate([notice,unknown],baseline.record,settings,now).alerts.length,2);
let silent=evaluate([notice],baseline.record,settings,time(23));assert.equal(silent.alerts.length,0);
let morning=evaluate([notice],silent.record,settings,time(31));assert.equal(morning.alerts.length,1);
assert.equal(evaluate([notice],morning.record,settings,time(32)).alerts.length,0);
assert.deepEqual(hours('24，6,1,1'),[24,6,1]);for(const v of ['', '0','NaN','-1','721','1,'])assert.throws(()=>hours(v));
console.log('In-app reminders: baseline, thresholds, dedup, completion, expiry, deadline changes, quiet hours, urgent override and custom times passed');
